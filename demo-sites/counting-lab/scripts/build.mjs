import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const endpoint = process.env.BUGSHIELD_ENDPOINT || 'https://buildshield-re.onrender.com/sdk/bugshield.js';
const key = process.env.BUGSHIELD_KEY || '';
const commit = process.env.RENDER_GIT_COMMIT || 'local';
fs.writeFileSync(path.join(root, 'config.js'),
  `// Generated by scripts/build.mjs\nwindow.BUGSHIELD_ENDPOINT = ${JSON.stringify(endpoint)};\nwindow.BUGSHIELD_KEY = ${JSON.stringify(key)};\nwindow.BUGSHIELD_BUILD_INFO = { commit: ${JSON.stringify(commit)} };\n`);
fs.writeFileSync(path.join(root, 'version.json'), JSON.stringify({ commit, service: 'counting-lab', generated: new Date().toISOString() }, null, 2) + '\n');
console.log('[build] counting-lab', commit);
